import Foundation
import Darwin

/// Checked, descriptor-anchored storage for the later conversation journal.
/// This type intentionally has no schema, retention, restore, or recorder wiring.
/// A caller supplies the app's already-selected state root; this initializer walks
/// that absolute path without following symlinks and then owns only fixed children.
enum ConversationPersistenceFilesError: Error, Equatable {
    case unsafeStateRoot
    case unsafeObject
    case lockUnavailable
    case tooLarge
    case ioFailure
    /// The rename completed but syncing its parent directory did not. The new
    /// bytes may be visible, but their durability across a crash is unknown.
    case committedButDurabilityUncertain
}

struct ConversationPersistenceGeneration: Hashable {
    let value: String

    private init(value: String) { self.value = value }

    /// An opaque store-controlled name, never derived from a session, content,
    /// persistent ID, route, or other captured value.
    static func make(uuid: UUID = UUID()) -> ConversationPersistenceGeneration {
        ConversationPersistenceGeneration(value: uuid.uuidString.lowercased())
    }

    /// Recovery accepts only the exact lower-case UUID spelling generated by
    /// this store; it never treats arbitrary index text as a filesystem name.
    init?(serialized value: String) {
        guard UUID(uuidString: value)?.uuidString.lowercased() == value else { return nil }
        self.value = value
    }
}

struct ConversationPersistenceRecordFile: Equatable {
    let generation: ConversationPersistenceGeneration
    let bytes: Int
}

/// Identifies the inode whose complete bytes were read for journal validation.
struct ConversationPersistenceRecordDeletionTicket {
    fileprivate let generation: ConversationPersistenceGeneration
    fileprivate let device: dev_t
    fileprivate let inode: ino_t
    fileprivate let bytes: Int
}

struct ConversationPersistenceEmptyTemporaryTicket {
    fileprivate let name: String
    fileprivate let directory: ConversationPersistenceFilesDirectory
    fileprivate let device: dev_t
    fileprivate let inode: ino_t
}

/// Narrow deterministic test controls. They only select opaque UUIDs, report
/// production I/O boundaries, or return a checked-I/O failure at that boundary;
/// they never skip a production validation step.
enum ConversationPersistenceFilesTestFault: Equatable {
    /// Test-only checked-I/O failure after temp identity capture. This exercises
    /// cleanup without skipping the production fchmod boundary.
    case temporaryFchmod
    case beforeRename
    case afterRenameBeforeDirectorySync
    case directoryParentSync(ConversationPersistenceFilesDirectory)
    case recordUnlink
    case recordUnlinkForGeneration(ConversationPersistenceGeneration)
    case recordUnlinkDirectorySync
}

enum ConversationPersistenceFilesDirectory: Equatable {
    case conversations
    case records
}

enum ConversationPersistenceFilesTestEvent: Equatable {
    case beforeDirectoryParentSync(ConversationPersistenceFilesDirectory)
    case afterTemporaryCreate(String)
    case beforeLateDestinationCheck(String)
    case beforePublish(String)
    case beforeRecordRemoval(ConversationPersistenceGeneration)
}

enum ConversationPersistenceIndexTestFault {
    case beforeRename
    case afterRenameBeforeDirectorySync
}

struct ConversationPersistenceFilesTestControl {
    let temporaryUUID: UUID?
    let recordUUID: UUID?
    let fault: ConversationPersistenceFilesTestFault?
    let indexFault: ConversationPersistenceIndexTestFault?
    let event: ((ConversationPersistenceFilesTestEvent) -> Void)?

    init(temporaryUUID: UUID? = nil, recordUUID: UUID? = nil,
         fault: ConversationPersistenceFilesTestFault? = nil,
         indexFault: ConversationPersistenceIndexTestFault? = nil,
         event: ((ConversationPersistenceFilesTestEvent) -> Void)? = nil) {
        self.temporaryUUID = temporaryUUID
        self.recordUUID = recordUUID
        self.fault = fault
        self.indexFault = indexFault
        self.event = event
    }
}

/// A single synchronous, single-writer lease. Keep one instance alive on the
/// later persistence queue for the recorder lifetime; its lock descriptor is
/// closed only when this object is released.
final class ConversationPersistenceFiles {
    static let maximumRecordBytes = 32 << 20
    static let maximumIndexBytes = 1 << 20
    static let maximumPhysicalRecords = 1_024

    private static let conversationsName = "Conversations"
    private static let recordsName = "records"
    private static let lockName = "lock"
    private static let indexName = "index-v1.json"

    private struct FileIdentity: Equatable {
        let device: dev_t
        let inode: ino_t
        init(_ info: stat) { device = info.st_dev; inode = info.st_ino }
    }

    private enum DestinationObservation: Equatable {
        case absent
        case present(FileIdentity)
    }

    private let stateRootFD: Int32
    private let conversationsFD: Int32
    private let recordsFD: Int32
    private let lockFD: Int32
    private let testControl: ConversationPersistenceFilesTestControl?

    /// `stateRootPath` must identify the state root selected by the forwarder,
    /// not a user/content-derived location. It is walked from `/` using FDs so
    /// no component below that root is subsequently addressed by path.
    init(verifiedStateRootPath stateRootPath: String,
         testControl: ConversationPersistenceFilesTestControl? = nil) throws {
        let root = try Self.openVerifiedStateRoot(stateRootPath)
        var conversations: Int32 = -1
        var records: Int32 = -1
        do {
            conversations = try Self.openOrCreateDirectory(named: Self.conversationsName, in: root,
                                                            link: .conversations, testControl: testControl)
            records = try Self.openOrCreateDirectory(named: Self.recordsName, in: conversations,
                                                      link: .records, testControl: testControl)
            let lock = try Self.openAndLock(named: Self.lockName, in: conversations)
            stateRootFD = root
            conversationsFD = conversations
            recordsFD = records
            lockFD = lock
            self.testControl = testControl
        } catch {
            if records >= 0 { Darwin.close(records) }
            if conversations >= 0 { Darwin.close(conversations) }
            Darwin.close(root)
            throw error
        }
    }

    deinit {
        Darwin.close(lockFD)
        Darwin.close(recordsFD)
        Darwin.close(conversationsFD)
        Darwin.close(stateRootFD)
    }

    func writeIndex(_ bytes: Data) throws {
        try Self.require(bytes.count <= Self.maximumIndexBytes)
        try verifyLease()
        try writeAtomically(bytes, named: Self.indexName, in: conversationsFD, replacing: true)
    }

    /// `nil` means that the bounded, verified index does not exist yet.
    func readIndex() throws -> Data? {
        try verifyLease()
        return try readFile(named: Self.indexName, in: conversationsFD, maximumBytes: Self.maximumIndexBytes)
    }

    @discardableResult
    func writeRecord(_ bytes: Data, generation requestedGeneration: ConversationPersistenceGeneration? = nil) throws -> ConversationPersistenceGeneration {
        try Self.require(bytes.count <= Self.maximumRecordBytes)
        try verifyLease()
        let generation = requestedGeneration ?? ConversationPersistenceGeneration.make(uuid: testControl?.recordUUID ?? UUID())
        try writeAtomically(bytes, named: Self.recordName(for: generation), in: recordsFD, replacing: false)
        return generation
    }

    func readRecord(_ generation: ConversationPersistenceGeneration) throws -> Data {
        try verifyLease()
        guard let data = try readFile(named: Self.recordName(for: generation), in: recordsFD,
                                      maximumBytes: Self.maximumRecordBytes) else {
            throw ConversationPersistenceFilesError.ioFailure
        }
        return data
    }

    /// Capture identity from the same checked read whose bytes the caller validates.
    func readRecordForDeletion(_ generation: ConversationPersistenceGeneration) throws -> (Data, ConversationPersistenceRecordDeletionTicket) {
        try verifyLease()
        guard let (data, info) = try readFileWithIdentity(named: Self.recordName(for: generation), in: recordsFD,
                                                          maximumBytes: Self.maximumRecordBytes) else {
            throw ConversationPersistenceFilesError.ioFailure
        }
        return (data, .init(generation: generation, device: info.st_dev, inode: info.st_ino, bytes: data.count))
    }

    /// Only a validated, durably unreferenced generation may be passed here.
    /// Binding checks narrow but cannot eliminate a same-UID race before unlink.
    func removeValidatedRecord(_ ticket: ConversationPersistenceRecordDeletionTicket) throws {
        try verifyLease()
        let name = Self.recordName(for: ticket.generation)
        testControl?.event?(.beforeRecordRemoval(ticket.generation))
        let descriptor = Darwin.openat(recordsFD, name, O_RDONLY | O_NONBLOCK | O_NOFOLLOW | O_CLOEXEC)
        guard descriptor >= 0 else { throw ConversationPersistenceFilesError.ioFailure }
        defer { Darwin.close(descriptor) }
        let info = try Self.verifyFileBinding(named: name, in: recordsFD, descriptor: descriptor,
                                              maximumBytes: Self.maximumRecordBytes, exactSize: off_t(ticket.bytes))
        guard info.st_dev == ticket.device, info.st_ino == ticket.inode else {
            throw ConversationPersistenceFilesError.unsafeObject
        }
        try verifyLease()
        _ = try Self.verifyFileBinding(named: name, in: recordsFD, descriptor: descriptor,
                                       maximumBytes: Self.maximumRecordBytes, exactSize: off_t(ticket.bytes))
        if testControl?.fault == .recordUnlink || testControl?.fault == .recordUnlinkForGeneration(ticket.generation) {
            throw ConversationPersistenceFilesError.ioFailure
        }
        guard unlinkat(recordsFD, name, 0) == 0 else { throw ConversationPersistenceFilesError.ioFailure }
        if testControl?.fault == .recordUnlinkDirectorySync { throw ConversationPersistenceFilesError.committedButDurabilityUncertain }
        guard fsync(recordsFD) == 0 else { throw ConversationPersistenceFilesError.committedButDurabilityUncertain }
    }

    /// Refuse unrecognized root objects and newer layouts. Canonical temporary
    /// names are separately checked for empty owned inodes before journal use.
    func validateConversationsNamespace() throws {
        try verifyLease()
        let scanFD = Darwin.openat(conversationsFD, ".", O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
        guard scanFD >= 0 else { throw ConversationPersistenceFilesError.ioFailure }
        guard let stream = fdopendir(scanFD) else { Darwin.close(scanFD); throw ConversationPersistenceFilesError.ioFailure }
        defer { closedir(stream) }
        var count = 0
        while true {
            errno = 0
            guard let entry = readdir(stream) else {
                guard errno == 0 else { throw ConversationPersistenceFilesError.ioFailure }
                break
            }
            let name = withUnsafePointer(to: entry.pointee.d_name) {
                $0.withMemoryRebound(to: CChar.self, capacity: Int(NAME_MAX) + 1) { String(cString: $0) }
            }
            if name == "." || name == ".." { continue }
            count += 1
            guard count <= Self.maximumPhysicalRecords + 3,
                  name == Self.recordsName || name == Self.lockName || name == Self.indexName || Self.isTemporaryName(name) else {
                throw ConversationPersistenceFilesError.unsafeObject
            }
        }
    }

    /// Bounded actual-file inventory for journal capacity checks. It opens a
    /// fresh directory descriptor instead of dup'ing the retained FD: dup
    /// shares a directory offset and can miss entries on repeated scans.
    func inventoryRecords() throws -> [ConversationPersistenceRecordFile] {
        try verifyLease()
        _ = try emptyTemporaryTickets()
        // A previous unlink may have succeeded without a durable directory
        // sync. Do not budget its absence until this sync succeeds, including
        // after a lease is reacquired by another journal instance.
        guard fsync(recordsFD) == 0 else { throw ConversationPersistenceFilesError.ioFailure }
        let scanFD = Darwin.openat(recordsFD, ".", O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
        guard scanFD >= 0 else { throw ConversationPersistenceFilesError.ioFailure }
        guard let stream = fdopendir(scanFD) else { Darwin.close(scanFD); throw ConversationPersistenceFilesError.ioFailure }
        defer { closedir(stream) }
        var entries: [ConversationPersistenceRecordFile] = []
        while true {
            errno = 0
            guard let entry = readdir(stream) else {
                guard errno == 0 else { throw ConversationPersistenceFilesError.ioFailure }
                break
            }
            let name = withUnsafePointer(to: entry.pointee.d_name) {
                $0.withMemoryRebound(to: CChar.self, capacity: Int(NAME_MAX) + 1) { String(cString: $0) }
            }
            if name == "." || name == ".." { continue }
            if Self.isTemporaryName(name) { continue }
            guard name.hasSuffix(".json"),
                  let generation = ConversationPersistenceGeneration(serialized: String(name.dropLast(5))) else {
                throw ConversationPersistenceFilesError.unsafeObject
            }
            let descriptor = Darwin.openat(recordsFD, name, O_RDONLY | O_NONBLOCK | O_NOFOLLOW | O_CLOEXEC)
            guard descriptor >= 0 else { throw ConversationPersistenceFilesError.unsafeObject }
            let info: stat
            do {
                info = try Self.verifyFileBinding(named: name, in: recordsFD, descriptor: descriptor,
                                                  maximumBytes: Self.maximumRecordBytes, exactSize: nil)
            } catch {
                Darwin.close(descriptor)
                throw error
            }
            Darwin.close(descriptor)
            guard entries.count < Self.maximumPhysicalRecords else { throw ConversationPersistenceFilesError.tooLarge }
            entries.append(.init(generation: generation, bytes: Int(info.st_size)))
        }
        return entries
    }

    private static func isTemporaryName(_ name: String) -> Bool {
        guard name.hasPrefix(".tmp-") else { return false }
        return ConversationPersistenceGeneration(serialized: String(name.dropFirst(5))) != nil
    }

    /// Empty, strictly owned temporary files are the only temporary files this
    /// version can classify for recovery. Nonempty and unknown bytes block.
    func emptyTemporaryTickets() throws -> [ConversationPersistenceEmptyTemporaryTicket] {
        try verifyLease()
        var tickets: [ConversationPersistenceEmptyTemporaryTicket] = []
        for (directory, fd) in [(ConversationPersistenceFilesDirectory.conversations, conversationsFD), (.records, recordsFD)] {
            let scanFD = Darwin.openat(fd, ".", O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
            guard scanFD >= 0 else { throw ConversationPersistenceFilesError.ioFailure }
            guard let stream = fdopendir(scanFD) else { Darwin.close(scanFD); throw ConversationPersistenceFilesError.ioFailure }
            defer { closedir(stream) }
            while true {
                errno = 0
                guard let entry = readdir(stream) else {
                    guard errno == 0 else { throw ConversationPersistenceFilesError.ioFailure }
                    break
                }
                let name = withUnsafePointer(to: entry.pointee.d_name) {
                    $0.withMemoryRebound(to: CChar.self, capacity: Int(NAME_MAX) + 1) { String(cString: $0) }
                }
                guard Self.isTemporaryName(name) else { continue }
                guard tickets.count < Self.maximumPhysicalRecords else { throw ConversationPersistenceFilesError.tooLarge }
                let descriptor = Darwin.openat(fd, name, O_RDONLY | O_NONBLOCK | O_NOFOLLOW | O_CLOEXEC)
                guard descriptor >= 0 else { throw ConversationPersistenceFilesError.unsafeObject }
                let info: stat
                do { info = try Self.verifyFileBinding(named: name, in: fd, descriptor: descriptor, maximumBytes: 0, exactSize: 0) }
                catch { Darwin.close(descriptor); throw error }
                Darwin.close(descriptor)
                tickets.append(.init(name: name, directory: directory, device: info.st_dev, inode: info.st_ino))
            }
        }
        return tickets
    }

    func removeEmptyTemporary(_ ticket: ConversationPersistenceEmptyTemporaryTicket) throws {
        try verifyLease()
        let fd = ticket.directory == .records ? recordsFD : conversationsFD
        let descriptor = Darwin.openat(fd, ticket.name, O_RDONLY | O_NONBLOCK | O_NOFOLLOW | O_CLOEXEC)
        guard descriptor >= 0 else { throw ConversationPersistenceFilesError.ioFailure }
        defer { Darwin.close(descriptor) }
        let info = try Self.verifyFileBinding(named: ticket.name, in: fd, descriptor: descriptor, maximumBytes: 0, exactSize: 0)
        guard info.st_dev == ticket.device, info.st_ino == ticket.inode else { throw ConversationPersistenceFilesError.unsafeObject }
        try verifyLease()
        _ = try Self.verifyFileBinding(named: ticket.name, in: fd, descriptor: descriptor, maximumBytes: 0, exactSize: 0)
        guard unlinkat(fd, ticket.name, 0) == 0 else { throw ConversationPersistenceFilesError.ioFailure }
        guard fsync(fd) == 0 else { throw ConversationPersistenceFilesError.committedButDurabilityUncertain }
    }

    /// Establish the current visible index as durable before treating any
    /// generation absent from it as unreferenced, including after a prior
    /// index-rename durability-uncertain result.
    func synchronizeIndexDirectory() throws {
        try verifyLease()
        guard fsync(conversationsFD) == 0 else { throw ConversationPersistenceFilesError.ioFailure }
    }

    /// Revalidates below-root bindings without reopening the external root path.
    /// This deliberately preserves the retained-root capability if an ancestor is
    /// renamed, while rejecting a replaced child directory or lock entry.
    private func verifyLease() throws {
        try Self.verifyDirectoryBinding(named: Self.conversationsName, in: stateRootFD, descriptor: conversationsFD)
        try Self.verifyDirectoryBinding(named: Self.recordsName, in: conversationsFD, descriptor: recordsFD)
        _ = try Self.verifyFileBinding(named: Self.lockName, in: conversationsFD, descriptor: lockFD,
                                       maximumBytes: 0, exactSize: 0)
    }

    private func writeAtomically(_ bytes: Data, named name: String, in directoryFD: Int32,
                                 replacing: Bool) throws {
        try Self.checkFixedName(name)
        try Self.verifyDirectory(directoryFD)
        let earlyDestination = try Self.observeDestination(named: name, in: directoryFD, replacing: replacing)
        let temporaryName = ".tmp-" + (testControl?.temporaryUUID ?? UUID()).uuidString.lowercased()
        var temporaryFD: Int32 = -1
        var createdIdentity: FileIdentity?
        var renamed = false
        defer {
            // Validate the owned inode while it is still open. A failed O_EXCL
            // create has no identity and cannot trigger cleanup; a substituted
            // pathname does not match and is deliberately preserved.
            if !renamed, temporaryFD >= 0, let createdIdentity {
                Self.unlinkOwnedTemporary(named: temporaryName, in: directoryFD, matching: createdIdentity)
            }
            if temporaryFD >= 0 { Darwin.close(temporaryFD) }
        }

        temporaryFD = Darwin.openat(directoryFD, temporaryName,
                                    O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW | O_CLOEXEC, 0o600)
        guard temporaryFD >= 0 else { throw ConversationPersistenceFilesError.ioFailure }
        // Arm identity-matched cleanup immediately after exclusive creation.
        // fchmod may fail, and a later pathname substitution must still never
        // be unlinked merely because this operation created an earlier inode.
        createdIdentity = try Self.checkedNewTemporaryIdentity(temporaryFD)
        if testControl?.fault == .temporaryFchmod { throw ConversationPersistenceFilesError.ioFailure }
        guard fchmod(temporaryFD, 0o600) == 0 else { throw ConversationPersistenceFilesError.ioFailure }
        _ = try Self.verifyRegularFile(temporaryFD, maximumBytes: bytes.count, exactSize: 0)
        testControl?.event?(.afterTemporaryCreate(temporaryName))
        try Self.verifyRegularFile(temporaryFD, maximumBytes: bytes.count, exactSize: 0)
        try Self.writeAll(bytes, to: temporaryFD)
        guard fsync(temporaryFD) == 0 else { throw ConversationPersistenceFilesError.ioFailure }
        try Self.verifyRegularFile(temporaryFD, maximumBytes: bytes.count, exactSize: off_t(bytes.count))
        try Self.verifyFileBinding(named: temporaryName, in: directoryFD, descriptor: temporaryFD,
                                   maximumBytes: bytes.count, exactSize: off_t(bytes.count))
        if testControl?.fault == .beforeRename || (name == Self.indexName && testControl?.indexFault == .beforeRename) { throw ConversationPersistenceFilesError.ioFailure }

        // This late lease and destination check narrows stale observations but
        // is not an atomic compare-and-replace guarantee against a same-UID
        // adversary after the check. Immutable records additionally use EXCL.
        try verifyLease()
        testControl?.event?(.beforeLateDestinationCheck(name))
        let lateDestination = try Self.observeDestination(named: name, in: directoryFD, replacing: replacing)
        guard lateDestination == earlyDestination else { throw ConversationPersistenceFilesError.unsafeObject }
        testControl?.event?(.beforePublish(name))
        let renamedOK: Bool
        if replacing {
            renamedOK = renameat(directoryFD, temporaryName, directoryFD, name) == 0
        } else {
            renamedOK = Self.renameExclusive(from: temporaryName, to: name, in: directoryFD)
        }
        guard renamedOK else { throw ConversationPersistenceFilesError.ioFailure }
        renamed = true
        do {
            _ = try Self.verifyFileBinding(named: name, in: directoryFD, descriptor: temporaryFD,
                                           maximumBytes: bytes.count, exactSize: off_t(bytes.count))
        } catch {
            // The commit point was crossed, but its current name binding and
            // crash durability can no longer be asserted.
            throw ConversationPersistenceFilesError.committedButDurabilityUncertain
        }
        if testControl?.fault == .afterRenameBeforeDirectorySync || (name == Self.indexName && testControl?.indexFault == .afterRenameBeforeDirectorySync) {
            throw ConversationPersistenceFilesError.committedButDurabilityUncertain
        }
        guard fsync(directoryFD) == 0 else {
            throw ConversationPersistenceFilesError.committedButDurabilityUncertain
        }
    }

    private func readFile(named name: String, in directoryFD: Int32, maximumBytes: Int) throws -> Data? {
        try readFileWithIdentity(named: name, in: directoryFD, maximumBytes: maximumBytes)?.0
    }

    private func readFileWithIdentity(named name: String, in directoryFD: Int32, maximumBytes: Int) throws -> (Data, stat)? {
        try Self.checkFixedName(name)
        try Self.verifyDirectory(directoryFD)
        let descriptor = Darwin.openat(directoryFD, name, O_RDONLY | O_NONBLOCK | O_NOFOLLOW | O_CLOEXEC)
        if descriptor < 0 {
            if errno == ENOENT { return nil }
            throw ConversationPersistenceFilesError.ioFailure
        }
        defer { Darwin.close(descriptor) }
        let before = try Self.verifyFileBinding(named: name, in: directoryFD, descriptor: descriptor,
                                                maximumBytes: maximumBytes, exactSize: nil)
        var data = Data()
        data.reserveCapacity(Int(before.st_size))
        var chunk = [UInt8](repeating: 0, count: 64 << 10)
        while true {
            let count = chunk.withUnsafeMutableBytes { Darwin.read(descriptor, $0.baseAddress, $0.count) }
            if count < 0 && errno == EINTR { continue }
            guard count >= 0 else { throw ConversationPersistenceFilesError.ioFailure }
            if count == 0 { break }
            data.append(contentsOf: chunk[0..<count])
            guard data.count <= maximumBytes else { throw ConversationPersistenceFilesError.tooLarge }
        }
        let after = try Self.verifyFileBinding(named: name, in: directoryFD, descriptor: descriptor,
                                               maximumBytes: maximumBytes, exactSize: before.st_size)
        guard after.st_dev == before.st_dev, after.st_ino == before.st_ino,
              data.count == Int(before.st_size) else { throw ConversationPersistenceFilesError.unsafeObject }
        return (data, after)
    }

    private static func openVerifiedStateRoot(_ path: String) throws -> Int32 {
        guard path.hasPrefix("/"), !path.utf8.contains(0) else { throw ConversationPersistenceFilesError.unsafeStateRoot }
        let parts = path.split(separator: "/", omittingEmptySubsequences: true)
        guard !parts.isEmpty, parts.allSatisfy({ $0 != "." && $0 != ".." }) else {
            throw ConversationPersistenceFilesError.unsafeStateRoot
        }
        var descriptor = Darwin.open("/", O_RDONLY | O_DIRECTORY | O_CLOEXEC)
        guard descriptor >= 0 else { throw ConversationPersistenceFilesError.ioFailure }
        for component in parts {
            let next = component.withCString {
                Darwin.openat(descriptor, $0, O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
            }
            Darwin.close(descriptor)
            guard next >= 0 else { throw ConversationPersistenceFilesError.unsafeStateRoot }
            descriptor = next
        }
        do {
            try verifyDirectory(descriptor)
            return descriptor
        } catch {
            Darwin.close(descriptor)
            throw error
        }
    }

    private static func openOrCreateDirectory(named name: String, in parentFD: Int32,
                                              link: ConversationPersistenceFilesDirectory,
                                              testControl: ConversationPersistenceFilesTestControl?) throws -> Int32 {
        try checkFixedName(name)
        try verifyDirectory(parentFD)
        if mkdirat(parentFD, name, 0o700) != 0 && errno != EEXIST {
            throw ConversationPersistenceFilesError.ioFailure
        }
        let descriptor = Darwin.openat(parentFD, name, O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
        guard descriptor >= 0 else { throw ConversationPersistenceFilesError.unsafeObject }
        do {
            // mkdirat requests 0700 and the strict post-create check rejects
            // any umask-narrowed result rather than chmodding a pre-existing or
            // replacement directory. Every verified link is synced, even if it
            // already existed, so a prior mkdir+failed-fsync is retried safely.
            try verifyDirectoryBinding(named: name, in: parentFD, descriptor: descriptor)
            testControl?.event?(.beforeDirectoryParentSync(link))
            if testControl?.fault == .directoryParentSync(link) { throw ConversationPersistenceFilesError.ioFailure }
            guard fsync(parentFD) == 0 else { throw ConversationPersistenceFilesError.ioFailure }
            return descriptor
        } catch {
            Darwin.close(descriptor)
            throw error
        }
    }

    private static func openAndLock(named name: String, in directoryFD: Int32) throws -> Int32 {
        try checkFixedName(name)
        try verifyDirectory(directoryFD)
        var descriptor = Darwin.openat(directoryFD, name,
                                       O_RDWR | O_CREAT | O_EXCL | O_NOFOLLOW | O_CLOEXEC, 0o600)
        if descriptor >= 0 {
            guard fchmod(descriptor, 0o600) == 0 else {
                Darwin.close(descriptor)
                throw ConversationPersistenceFilesError.ioFailure
            }
        } else if errno == EEXIST {
            descriptor = Darwin.openat(directoryFD, name, O_RDWR | O_NONBLOCK | O_NOFOLLOW | O_CLOEXEC)
        }
        guard descriptor >= 0 else { throw ConversationPersistenceFilesError.unsafeObject }
        do {
            _ = try verifyFileBinding(named: name, in: directoryFD, descriptor: descriptor,
                                      maximumBytes: 0, exactSize: 0)
            guard flock(descriptor, LOCK_EX | LOCK_NB) == 0 else {
                if errno == EWOULDBLOCK || errno == EAGAIN { throw ConversationPersistenceFilesError.lockUnavailable }
                throw ConversationPersistenceFilesError.ioFailure
            }
            _ = try verifyFileBinding(named: name, in: directoryFD, descriptor: descriptor,
                                      maximumBytes: 0, exactSize: 0)
            return descriptor
        } catch {
            Darwin.close(descriptor)
            throw error
        }
    }

    private static func observeDestination(named name: String, in directoryFD: Int32,
                                           replacing: Bool) throws -> DestinationObservation {
        var info = stat()
        if fstatat(directoryFD, name, &info, AT_SYMLINK_NOFOLLOW) == 0 {
            guard replacing else { throw ConversationPersistenceFilesError.unsafeObject }
            try verifyStatRegular(info, maximumBytes: Self.maximumIndexBytes, exactSize: nil)
            return .present(FileIdentity(info))
        }
        guard errno == ENOENT else { throw ConversationPersistenceFilesError.ioFailure }
        return .absent
    }

    private static func renameExclusive(from source: String, to destination: String, in directoryFD: Int32) -> Bool {
        source.withCString { sourcePointer in
            destination.withCString { destinationPointer in
                Darwin.renameatx_np(directoryFD, sourcePointer, directoryFD, destinationPointer, UInt32(RENAME_EXCL)) == 0
            }
        }
    }

    private static func verifyDirectory(_ descriptor: Int32) throws {
        var info = stat()
        guard fstat(descriptor, &info) == 0 else { throw ConversationPersistenceFilesError.ioFailure }
        guard info.st_mode & S_IFMT == S_IFDIR, info.st_uid == getuid(), info.st_mode & 0o777 == 0o700 else {
            throw ConversationPersistenceFilesError.unsafeObject
        }
    }

    private static func verifyDirectoryBinding(named name: String, in parentFD: Int32, descriptor: Int32) throws {
        try verifyDirectory(descriptor)
        var pathInfo = stat()
        var descriptorInfo = stat()
        guard fstatat(parentFD, name, &pathInfo, AT_SYMLINK_NOFOLLOW) == 0,
              fstat(descriptor, &descriptorInfo) == 0,
              pathInfo.st_mode & S_IFMT == S_IFDIR,
              pathInfo.st_dev == descriptorInfo.st_dev, pathInfo.st_ino == descriptorInfo.st_ino else {
            throw ConversationPersistenceFilesError.unsafeObject
        }
    }

    @discardableResult
    private static func verifyFileBinding(named name: String, in directoryFD: Int32, descriptor: Int32,
                                          maximumBytes: Int, exactSize: off_t?) throws -> stat {
        let info = try verifyRegularFile(descriptor, maximumBytes: maximumBytes, exactSize: exactSize)
        var pathInfo = stat()
        guard fstatat(directoryFD, name, &pathInfo, AT_SYMLINK_NOFOLLOW) == 0,
              pathInfo.st_mode & S_IFMT == S_IFREG,
              pathInfo.st_dev == info.st_dev, pathInfo.st_ino == info.st_ino else {
            throw ConversationPersistenceFilesError.unsafeObject
        }
        return info
    }

    @discardableResult
    private static func verifyRegularFile(_ descriptor: Int32, maximumBytes: Int,
                                          exactSize: off_t?) throws -> stat {
        var info = stat()
        guard fstat(descriptor, &info) == 0 else { throw ConversationPersistenceFilesError.ioFailure }
        try verifyStatRegular(info, maximumBytes: maximumBytes, exactSize: exactSize)
        return info
    }

    private static func verifyStatRegular(_ info: stat, maximumBytes: Int, exactSize: off_t?) throws {
        guard info.st_mode & S_IFMT == S_IFREG, info.st_uid == getuid(), info.st_mode & 0o777 == 0o600,
              info.st_nlink == 1 else { throw ConversationPersistenceFilesError.unsafeObject }
        guard info.st_size >= 0, info.st_size <= off_t(maximumBytes) else { throw ConversationPersistenceFilesError.tooLarge }
        if let exactSize, info.st_size != exactSize { throw ConversationPersistenceFilesError.unsafeObject }
    }

    private static func writeAll(_ data: Data, to descriptor: Int32) throws {
        var written = 0
        try data.withUnsafeBytes { raw in
            while written < raw.count {
                let base = raw.baseAddress!.advanced(by: written)
                let count = Darwin.write(descriptor, base, raw.count - written)
                if count < 0 && errno == EINTR { continue }
                guard count > 0 else { throw ConversationPersistenceFilesError.ioFailure }
                written += count
            }
        }
    }

    /// This intentionally checks only facts stable across the immediately
    /// following fchmod: the freshly opened inode is private, regular, empty,
    /// and owned by this UID. Exact 0600 verification follows fchmod.
    private static func checkedNewTemporaryIdentity(_ descriptor: Int32) throws -> FileIdentity {
        var info = stat()
        guard fstat(descriptor, &info) == 0 else { throw ConversationPersistenceFilesError.ioFailure }
        guard info.st_mode & S_IFMT == S_IFREG, info.st_uid == getuid(), info.st_nlink == 1, info.st_size == 0 else {
            throw ConversationPersistenceFilesError.unsafeObject
        }
        return FileIdentity(info)
    }

    private static func unlinkOwnedTemporary(named name: String, in directoryFD: Int32, matching identity: FileIdentity) {
        var info = stat()
        guard fstatat(directoryFD, name, &info, AT_SYMLINK_NOFOLLOW) == 0,
              FileIdentity(info) == identity,
              info.st_mode & S_IFMT == S_IFREG, info.st_uid == getuid(), info.st_mode & 0o777 == 0o600,
              info.st_nlink == 1 else { return }
        _ = unlinkat(directoryFD, name, 0)
    }

    private static func recordName(for generation: ConversationPersistenceGeneration) -> String {
        generation.value + ".json"
    }

    private static func checkFixedName(_ name: String) throws {
        guard !name.isEmpty, !name.contains("/"), !name.contains("\0"), name != ".", name != ".." else {
            throw ConversationPersistenceFilesError.unsafeObject
        }
    }

    private static func require(_ condition: Bool) throws {
        guard condition else { throw ConversationPersistenceFilesError.tooLarge }
    }
