import Foundation
import Darwin

@main @MainActor private struct HcWorkspacePresentationTests {
    static func main() {
        var n = 0
        func check(_ condition: Bool, _ label: String) { precondition(condition, label); n += 1 }
        let state = HcWorkspacePresentation(), epoch = UUID(), other = UUID(), tab = UUID(), a = UUID(), b = UUID()
        let first = HcSelectionStamp(tab: tab, pane: a), second = HcSelectionStamp(tab: tab, pane: b)
        check(!state.hasSelection && state.keyboardRequest == nil, "no unscoped selection")
        state.scopeChanged(epoch, focus: first)
        check(state.hasSelection && state.epoch == epoch, "restore selection in actual UI scope")
        state.clearSelection(focus: first)
        state.followFocus(first)
        check(!state.hasSelection, "mode change stays unselected despite unchanged model focus")
        state.select(first, requestKeyboard: false)
        check(state.hasSelection && state.keyboardRequest == nil, "list keyboard navigation does not steal focus")
        state.select(first, requestKeyboard: true)
        let token = state.keyboardRequest?.token
        check(state.keyboardRequest?.pane == a && state.keyboardRequest?.epoch == epoch, "explicit row activation requests exact scoped pane")
        state.select(first, requestKeyboard: true)
        check(state.keyboardRequest?.token != token, "clicking the same row requests keyboard again")
        let currentToken = state.keyboardRequest!.token
        state.acknowledgeKeyboard(UUID())
        check(state.keyboardRequest?.token == currentToken, "late acknowledgement cannot retire a newer request")
        state.acknowledgeKeyboard(currentToken)
        check(state.keyboardRequest == nil && state.hasSelection, "successful focus is consumed, not replayed by overlay updates")
        state.previewCoversTerminal = true
        state.select(second, requestKeyboard: true)
        check(!state.previewCoversTerminal && state.keyboardRequest?.pane == b, "activation reveals the terminal")
        state.clearSelection(focus: second)
        state.followFocus(second)
        check(!state.hasSelection, "close result cannot immediately resurrect reconciled fallback selection")
        state.followFocus(first)
        check(state.hasSelection, "a genuinely different launch/selection can become visible")
        state.scopeChanged(other, focus: nil)
        check(!state.hasSelection && state.keyboardRequest == nil && !state.previewCoversTerminal, "scope change drops old UI/focus intent")
        state.select(first, requestKeyboard: true)
        check(state.keyboardRequest?.epoch == other, "new intent is stamped with current scope, not an old epoch")
        state.scopeChanged(nil, focus: nil)
        state.select(first, requestKeyboard: true)
        check(!state.hasSelection && state.keyboardRequest == nil, "retired scope cannot activate")
        func viewed(_ grouped: Bool, selected: Bool = true, key: Bool = true, covered: Bool = false, zoom: UUID? = nil) -> Set<UUID> {
            HcWorkspacePresentation.viewedPanes(panes: [a,b], focused: a, zoom: zoom, grouped: grouped,
                selected: selected, windowIsKey: key, covered: covered)
        }
        check(viewed(false) == [a], "pane mode does not mark a hidden sibling viewed")
        check(viewed(true) == [a,b], "tab mode sees its displayed panes")
        check(viewed(true,zoom:b) == [b], "zoom sees only its displayed pane")
        check(viewed(true,selected:false).isEmpty, "no UI selection is not viewed")
        check(viewed(true,key:false).isEmpty, "background window is not viewed")
        check(viewed(true,covered:true).isEmpty, "covered surface is not viewed when caller applies cover policy")
        check(viewed(true,zoom:UUID()).isEmpty, "unknown zoom does not broaden viewed scope")
        check(HcBoardSearch.matches("project claude",fields:["Project A","Claude Code"]), "search terms match across original workspace/title fields")
        check(HcBoardSearch.matches("  PROject  ",fields:["project A"]), "search ignores casing and empty whitespace terms")
        check(!HcBoardSearch.matches("project missing",fields:["project A","Shell"]), "all search terms must match, not any one term")
        state.scopeChanged(epoch,focus:first)
        let closingIntent = state.selectionIntent
        state.followFocus(second)
        check(state.selectionIntent == closingIntent, "model reconciliation is not a new explicit selection intent")
        state.clearSelection(ifUnchanged:closingIntent,focus:second)
        check(!state.hasSelection, "unchanged close intent clears reconciled fallback")
        state.select(first,requestKeyboard:false)
        let superseded = state.selectionIntent
        state.select(second,requestKeyboard:true)
        check(state.selectionIntent != superseded, "explicit row navigation retires pending close-selection intent")
        state.clearSelection(ifUnchanged:superseded,focus:first)
        check(state.hasSelection && state.keyboardRequest?.pane == b, "late close completion preserves newer row selection and keyboard intent")
        let previousScopeIntent = state.selectionIntent
        state.scopeChanged(other,focus:first)
        check(state.selectionIntent != previousScopeIntent, "scope change retires old close-selection completion")
        let revision = HcWorkspaceMutationStamp(epoch:epoch,coreID:"core",version:9007199254740993)
        check(revision.matches(epoch:epoch,coreID:"core",version:9007199254740993), "exact caller close baseline")
        check(!revision.matches(epoch:other,coreID:"core",version:revision.version), "different connection epoch refused")
        check(!revision.matches(epoch:nil,coreID:"core",version:revision.version), "retired connection refused")
        check(!revision.matches(epoch:epoch,coreID:"other",version:revision.version), "different permanent origin refused")
        check(!revision.matches(epoch:epoch,coreID:nil,version:revision.version), "unavailable origin refused")
        check(!revision.matches(epoch:epoch,coreID:"core",version:nil), "missing snapshot refused")
        check(!revision.matches(epoch:epoch,coreID:"core",version:revision.version-1), "large UInt64 revisions are never rounded")
        check(!revision.matches(epoch:epoch,coreID:"core",version:revision.version+1), "newer snapshot does not authorize automatic rebase")
        let exhausted = HcWorkspaceMutationStamp(epoch:epoch,coreID:"core",version:UInt64.max)
        check(exhausted.matches(epoch:epoch,coreID:"core",version:UInt64.max), "stamp comparison never overflows; store separately refuses exhausted writes")
        check(!HcWorkspaceMutationStamp(epoch:epoch,coreID:"",version:0).matches(epoch:epoch,coreID:"",version:0), "empty origin is never a close baseline")
        state.scopeChanged(epoch,focus:first)
        state.select(first,requestKeyboard:true)
        let oldKeyboard = state.keyboardRequest!
        state.textEditingBegan()
        check(state.textFieldOwnsKeyboard && state.inputGeneration != oldKeyboard.inputGeneration, "native editing retires older terminal keyboard intent immediately")
        let typingGeneration = state.inputGeneration
        state.textEditingEnded()
        check(!state.textFieldOwnsKeyboard && state.inputGeneration == typingGeneration, "ending editing never revives obsolete focus")
        state.select(first,requestKeyboard:true)
        check(state.keyboardRequest?.inputGeneration == typingGeneration, "new explicit row intent may take keyboard back from the field")
        state.textEditingBegan()
        let beforeTyping = state.inputGeneration
        state.textEditingBegan()
        check(state.inputGeneration != beforeTyping, "typing in an existing editor is a newer input intent too")
        state.scopeChanged(other,focus:first)
        check(state.textFieldOwnsKeyboard && state.keyboardRequest == nil, "scope reset drops terminal requests, not real editor ownership")
        state.textEditingEnded()
        state.scopeChanged(epoch,focus:first)
        state.select(first,requestKeyboard:false)
        let closePending = state.beginSelectedClose(focus:first)
        check(!state.hasSelection && state.keyboardRequest == nil,"confirmed selected close immediately retires its input surface")
        state.followFocus(second)
        check(!state.hasSelection,"layout fallback stays hidden while end RPC is pending")
        state.select(second,requestKeyboard:true)
        state.finishSelectedClose(closePending,focus:first)
        check(state.hasSelection && state.keyboardRequest?.pane == b,"new explicit row selection supersedes an in-flight close projection")
        let anotherClose = state.beginSelectedClose(focus:second)
        state.followFocus(first); state.finishSelectedClose(anotherClose,focus:first); state.followFocus(first)
        check(!state.hasSelection,"finishing close cannot resurrect its reconciled fallback")
        print("PASS workspace presentation rules: \(n) checks; not physical fullscreen/UI approval")
    }
}
